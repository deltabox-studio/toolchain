#!/usr/bin/env node
/**
 * Generate `packages/shared/src/config-types.ts` from `dbxConfigSchema`.
 *
 *   yarn config:types
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
    createConfigEngine,
    formatGenerated,
    type GenerateTypesOptions,
} from '@deltabox/toolchain-config';
import { dbxConfigSchema, logger } from '@deltabox/toolchain-shared';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const header = '// Generated by @deltabox/toolchain — do not edit.';

const overrides = {
    // `Record<string, ConfigJsonValue>` is not a legal recursive alias, so use
    // an index-signature object literal for the JSON value type.
    ConfigJsonValue: `export type ConfigJsonValue =
    | string
    | number
    | boolean
    | null
    | ConfigJsonValue[]
    | { [key: string]: ConfigJsonValue };`,
    ToolchainViteConfig: `export type ToolchainViteConfig = Omit<ViteUserConfig, 'fmt' | 'lint'> & {
    /** Write the managed Vite config (default true); a string sets its file name/path. */
    config?: boolean | string;
    /** Render the shim at runtime (default) or as a fully static config. */
    shim?: 'runtime' | 'static';
    /** Module specifier used to import resolveVite in runtime shims. */
    shimImport?: string;
    /** Oxfmt options; \`true\` uses the toolchain defaults. */
    fmt?: boolean | NonNullable<ViteUserConfig['fmt']>;
    /** Oxlint options; \`true\` uses the toolchain defaults. */
    lint?: boolean | NonNullable<ViteUserConfig['lint']>;
};`,
    // The custom logger carries functions, so it needs the hand-written type.
    ToolchainLoggerConfig: `export interface ToolchainLoggerConfig {
    /** Minimum level to print (default \`info\`). */
    level?: 'debug' | 'info' | 'warn' | 'error' | 'silent';
    /** Force colours on/off (default: on; \`--no-color\` disables). */
    color?: boolean;
    /** Prefix non-indented lines with \`<name>:\` (default \`dbx\`). */
    name?: string;
    /** Warning/error id, message substring, or \`/regex/\` to silence (single value or array). */
    suppress?: string | Array<string>;
    /** Custom logger implementation (TS/JS configs only). */
    logger?: ToolchainLogger;
    /** Enable/disable this section (default: enabled when defined). */
    enabled?: boolean;
}`,
} satisfies GenerateTypesOptions['overrides'];

const imports = [
    "import type { Configuration as DprintConfig } from '@dprint/types';",
    "import type { Linter } from 'eslint';",
    "import type { Options as PrettierConfig } from 'prettier';",
    "import type { JsonObject, TsConfigJson } from 'type-fest';",
    "import type { ViteUserConfig } from 'vite-plus';",
    "import type { BiomeConfig } from './config-schema/generated/biome-config.js';",
    "import type { ChangelogBreakingCommit } from './changelog-breaking.js';",
    "import type { ChangelogGroupContext, ChangelogGroupsContext, ChangelogGroupsSetting } from './changelog-groups.js';",
    "import type { ChangelogBumpRuleCallbackContext, ChangelogCommitFormatContext, ChangelogProviderContext } from './changelog-callbacks.js';",
    "import type { ToolchainLogger } from './logger.js';",
    "import type { ToolchainOxfmtConfig, ToolchainOxlintConfig } from './vite-defaults.js';",
];
const engine = createConfigEngine({ schema: dbxConfigSchema });
const types = engine.generateConfigTypes({ overrides, imports });
const sections = Object.values(types).map(content => content.trimEnd());
const content = `${[header, imports.join('\n'), ...sections].filter(Boolean).join('\n\n')}\n`;

const outPath = path.join(root, 'packages/shared/src/config-types.ts');
fs.writeFileSync(outPath, await formatGenerated(content, { fileName: outPath }), 'utf-8');

logger.info(`Generated ${path.relative(root, outPath)}`);
