#!/usr/bin/env node
/**
 * Generate `packages/shared/src/config-types.ts` from `dbxConfigSchema`.
 *
 *   yarn config:types
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
    createConfigEngine,
    formatGenerated,
    type GenerateTypesOptions,
} from '@deltabox/toolchain-config';
import { dbxConfigSchema, logger } from '@deltabox/toolchain-shared';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const header = '// Generated by @deltabox/toolchain — do not edit.';

const overrides = {
    ToolchainViteConfig: `export type ToolchainViteConfig = Omit<ViteUserConfig, 'fmt' | 'lint'> & {
    /** Write the managed Vite config (default true); a string sets its file name/path. */
    config?: boolean | string;
    /** Render the shim at runtime (default) or as a fully static config. */
    shim?: 'runtime' | 'static';
    /** Module specifier used to import resolveVite in runtime shims. */
    shimImport?: string;
    /** Oxfmt options; \`true\` uses the toolchain defaults. */
    fmt?: boolean | NonNullable<ViteUserConfig['fmt']>;
    /** Oxlint options; \`true\` uses the toolchain defaults. */
    lint?: boolean | NonNullable<ViteUserConfig['lint']>;
};`,
    // Type the override bodies as real tsconfigs (the schema keeps them open records).
    ToolchainTsconfigOverrides: `export interface ToolchainTsconfigOverrides {
    /** Deep-merged into the root base tsconfig (\`baseFile\`) during sync. */
    base?: TsConfigJson;
    /** Deep-merged into every workspace default tsconfig (\`defaultFile\`) during sync. */
    default?: TsConfigJson;
    /** Deep-merged into every workspace build tsconfig (\`buildFile\`) during sync. */
    build?: TsConfigJson;
    /** Deep-merged into the root workspaces tsconfig (\`rootFile\`) during sync. */
    root?: TsConfigJson;
}`,
} satisfies GenerateTypesOptions['overrides'];

const imports = [
    "import type { TsConfigJson } from 'type-fest';",
    "import type { ViteUserConfig } from 'vite-plus';",
];
const engine = createConfigEngine({ schema: dbxConfigSchema });
const types = engine.generateConfigTypes({ overrides, imports });
const sections = Object.values(types).map(content => content.trimEnd());
const content = `${[header, imports.join('\n'), ...sections].filter(Boolean).join('\n\n')}\n`;

const outPath = path.join(root, 'packages/shared/src/config-types.ts');
fs.writeFileSync(outPath, await formatGenerated(content, { fileName: outPath }), 'utf-8');

logger.info(`Generated ${path.relative(root, outPath)}`);
