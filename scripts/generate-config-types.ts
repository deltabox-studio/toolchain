#!/usr/bin/env node
/**
 * Generate `packages/shared/src/config-types.ts` from the Zod config model in
 * `packages/shared/src/config-schema.ts`, using the generic config engine's
 * type generator (`renderConfigTypes`).
 *
 *   yarn config:types
 */

import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { renderConfigTypes, resolveScopeSchema } from '@deltabox/toolchain-config';
import { CONFIG_TYPE_SCHEMAS } from '@deltabox/toolchain-shared';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));

const header = '// Generated by @deltabox/toolchain — do not edit. Run `yarn config:types`.';

const sections = Object.entries(CONFIG_TYPE_SCHEMAS).map(([typeName, zodSchema]) =>
    renderConfigTypes(typeName, resolveScopeSchema(undefined, zodSchema), {
        interfaceNames: { [typeName]: typeName },
    }).trimEnd()
);

const content = `${[header, ...sections].join('\n\n')}\n`;
const outPath = path.join(root, 'packages/shared/src/config-types.ts');
fs.writeFileSync(outPath, content, 'utf-8');

// Match the repo's Oxfmt config so the generated file is committed formatted.
try {
    const vp = path.join(
        root,
        'node_modules',
        '.bin',
        process.platform === 'win32' ? 'vp.cmd' : 'vp'
    );
    execSync(`"${vp}" fmt "${outPath}" --write`, { cwd: root, stdio: 'ignore' });
} catch {
    // Formatting is best-effort; the raw file is still valid TypeScript.
}

console.log(`Generated ${path.relative(root, outPath)}`);
