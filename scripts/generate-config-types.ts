#!/usr/bin/env node
/**
 * Generate `packages/shared/src/config-types.ts` from the Zod config model in
 * `packages/shared/src/config-schema.ts`, using the generic config engine's
 * type generator (`renderConfigTypes`).
 *
 *   yarn config:types
 *
 * Every type is derived from `CONFIG_TYPE_SCHEMAS` except `ToolchainViteConfig`,
 * which is a hand-written override (Vite+'s own `ViteUserConfig`, augmented with
 * the single toolchain opt-out `config`). The matching `import type` is emitted
 * at the top of the file through the generator's `imports` option.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
    formatGenerated,
    type GenerateTypesOptions,
    renderConfigImports,
    renderConfigTypes,
    resolveScopeSchema,
} from '@deltabox/toolchain-config';
import { CONFIG_TYPE_SCHEMAS, logger } from '@deltabox/toolchain-shared';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));

const header = '// Generated by @deltabox/toolchain — do not edit.';

/**
 * Hand-written type overrides, keyed by the `CONFIG_TYPE_SCHEMAS` key they
 * replace. `vite` is Vite+'s own config (Vite's `UserConfig`, which Vite+
 * augments) rather than a loose object, so `toolchain.vite` is fully typed.
 */
const overrides = {
    ToolchainViteConfig: `export type ToolchainViteConfig = ViteUserConfig & {
    /** Write the managed \`vite.config.ts\` (default true). */
    config?: boolean;
};`,
} satisfies GenerateTypesOptions['overrides'];

/** Imports referenced by the overrides, emitted once after the header. */
const imports = ["import type { ViteUserConfig } from 'vite-plus';"];

const sections = Object.entries(CONFIG_TYPE_SCHEMAS).map(([typeName, zodSchema]) =>
    renderConfigTypes(typeName, resolveScopeSchema(undefined, zodSchema), {
        interfaceNames: { [typeName]: typeName },
        overrides,
        imports,
    }).trimEnd()
);

const content = `${[header, renderConfigImports({ imports }), ...sections]
    .filter(Boolean)
    .join('\n\n')}\n`;
const outPath = path.join(root, 'packages/shared/src/config-types.ts');
// Format at generation time (Oxfmt programmatic API) rather than shelling out
// to the repo-root `vp`, so the committed file is written already formatted.
fs.writeFileSync(outPath, await formatGenerated(content, { fileName: outPath }), 'utf-8');

logger.info(`Generated ${path.relative(root, outPath)}`);
