import { describe, expect, it } from 'vitest';

import type { SyncContext, ToolchainConfig } from '@deltabox/toolchain-shared';

import { changelogSyncTask } from '../src/index.js';

function makeContext(config: ToolchainConfig): SyncContext {
    return {
        cwd: '/repo',
        projectType: 'monorepo-root',
        config,
        tokens: {},
        log: () => {},
        warn: () => {},
    };
}

describe('changelogSyncTask', () => {
    it('writes a husky commit-msg hook that runs commitlint', async () => {
        const files = await changelogSyncTask().run(makeContext({ changelog: {} }));
        const hook = files?.find(file => file.path === '.husky/commit-msg');
        expect(hook).toBeDefined();
        // The exact body matters: husky runs the hook with `sh -e`, so the
        // trailing newline and the `npx --no` (no network install) are load-bearing.
        expect(hook?.content).toBe(
            '# Generated by @deltabox/toolchain — edit dbx.config.* and run `dbx sync`.\nnpx --no -- commitlint --edit "$1"\n'
        );
    });

    it('still writes the commitlint config alongside the hook', async () => {
        const files = await changelogSyncTask().run(makeContext({ changelog: {} }));
        expect(files?.some(file => file.path === 'commitlint.config.mjs')).toBe(true);
    });

    it('writes a raw string workflow verbatim, with no generated header', async () => {
        const raw = 'name: Custom CI\non: [push]\n';
        const files = await changelogSyncTask().run(
            makeContext({ changelog: { workflows: { ci: raw } } })
        );
        const ci = files?.find(file => file.path === '.github/workflows/ci.yml');
        expect(ci?.content).toBe(raw);
    });

    it('prepends the generated header to built workflows', async () => {
        const files = await changelogSyncTask().run(makeContext({ changelog: {} }));
        const ci = files?.find(file => file.path === '.github/workflows/ci.yml');
        expect(ci?.content.startsWith('# Generated by @deltabox/toolchain')).toBe(true);
    });

    it('writes commitlint.config.mjs to a custom dir and points the hook + CI at it', async () => {
        const files = await changelogSyncTask().run(
            makeContext({ changelog: { commitlint: { dir: '.config' } } })
        );
        expect(files?.some(file => file.path === '.config/commitlint.config.mjs')).toBe(true);
        const hook = files?.find(file => file.path === '.husky/commit-msg');
        expect(hook?.content).toContain('--config .config/commitlint.config.mjs');
        const ci = files?.find(file => file.path === '.github/workflows/ci.yml');
        expect(ci?.content).toContain('--config .config/commitlint.config.mjs');
    });
});
