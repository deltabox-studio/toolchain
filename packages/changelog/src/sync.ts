/**
 * Apply the `ci.changelog.branches` defaults to a workflow's config. An explicit
 * per-workflow `pushBranches` (or `false` to disable) still wins, and a raw
 * string setting is left untouched (it defines its own triggers). Only the
 * workflows the consumer opted into are touched.
 */
function withPushBranches(
    setting: WorkflowSetting | undefined,
    branches: string[]
): WorkflowSetting {
    if (setting === false) return { enabled: false };
    if (typeof setting === 'string') return setting;
    // A complete vendor workflow defines its own triggers.
    if (isVendorWorkflowSetting(setting)) return setting;
    if (setting === true || setting === undefined) return { pushBranches: branches };
    return { pushBranches: branches, ...(setting as WorkflowOptions) };
}

/** Whether a workflow setting opts out of regeneration. */
function workflowRegenerates(setting: unknown): boolean {
    if (!setting || typeof setting !== 'object' || Array.isArray(setting)) return true;
    return (setting as { regenerate?: unknown }).regenerate !== false;
}

/** Whether the release workflow should mark prerelease versions on GitHub. */
function releasePrerelease(setting: unknown): boolean | 'auto' {
    if (!setting || typeof setting !== 'object' || Array.isArray(setting)) return 'auto';
    const value = (setting as { prerelease?: unknown }).prerelease;
    if (value === true || value === false || value === 'auto') return value;
    return 'auto';
}

/** Whether a resolved changelog config selects the changesets provider. */
function usesChangesetsProvider(
    config: ReturnType<typeof resolveChangelogConfig> | undefined
): boolean {
    const versioning = config?.versioning;
    if (!versioning || typeof versioning !== 'object') return false;
    const provider = versioning.provider;
    const entries = Array.isArray(provider) ? provider : [provider];
    return entries.some(entry => {
        if (entry === 'changesets') return true;
        return Boolean(
            entry &&
            typeof entry === 'object' &&
            (entry as { options?: unknown }).options === 'changesets'
        );
    });
}

/** The workflow settings declared under `toolchain.ci` (all opt-in). */
function declaredWorkflows(config: ToolchainConfig): Partial<Record<WorkflowId, WorkflowSetting>> {
    const ci = sectionEnabled(config.ci) ? (sectionConfig(config.ci) ?? {}) : {};
    const workflows: Partial<Record<WorkflowId, WorkflowSetting>> = {
        ci: ci.ci,
        changelog: ci.changelog as WorkflowSetting | undefined,
        release: ci.release,
        issues: ci.issues,
        sync: ci.sync,
    };
    for (const key of Object.keys(workflows) as WorkflowId[]) {
        if (!workflowRegenerates(workflows[key])) delete workflows[key];
    }
    return workflows;
}

/**
 * Map `ci.changelog.branches` onto the declared workflows: `main` drives CI +
 * release (and the release PR base), `dev` drives the changelog workflow
 * (reusing `main` when omitted), and `sync` runs on both.
 */
function withBranchDefaults(
    workflows: Partial<Record<WorkflowId, WorkflowSetting>>,
    branches: { main: string[]; dev: string[] }
): Partial<Record<WorkflowId, WorkflowSetting>> {
    const next = { ...workflows };
    const apply = (id: WorkflowId, list: string[]): void => {
        if (next[id] === undefined) return;
        next[id] = withPushBranches(next[id], list);
    };
    apply('ci', branches.main);
    apply('release', branches.main);
    apply('changelog', branches.dev);
    apply('sync', [...new Set([...branches.main, ...branches.dev])]);
    return next;
}

/** The header prepended to every generated GitHub workflow. */
export const WORKFLOW_HEADER = '# Generated by @deltabox/toolchain.';

/** The pre-3.0 header, still recognized so existing files remain dbx-owned. */
export const LEGACY_WORKFLOW_HEADER =
    '# Generated by @deltabox/toolchain — edit dbx.config.* and run `dbx sync`.';

/** The header prepended to the generated commitlint config. */
export const COMMITLINT_HEADER = '// Generated by @deltabox/toolchain.';

/** The header prepended to the generated commit hook. */
export const HOOK_HEADER = '# Generated by @deltabox/toolchain.';

/** The project-owned Vite+ commit hook (used when Vite+ is declared). */
export const VITE_COMMIT_HOOK_PATH = '.vite-hooks/commit-msg';

/** The husky commit hook (fallback for projects without Vite+). */
export const HUSKY_COMMIT_HOOK_PATH = '.husky/commit-msg';

/**
 * The commit-msg hook path for a project. Vite+ projects use the dispatcher
 * Vite+ owns (`.vite-hooks`, installed by `vp hooks enable` / `vp config`);
 * projects without Vite+ keep the husky fallback. `vp` treats `HUSKY=0` and the
 * husky init script the same way, but it never reads `.husky/` unless husky
 * installed its own dispatcher there.
 */
export function commitHookPath(cwd: string = process.cwd()): string {
    return declaresVitePlus(cwd) ? VITE_COMMIT_HOOK_PATH : HUSKY_COMMIT_HOOK_PATH;
}

/**
 * The commit-msg hook body. Vite+ and husky both run the hook with `sh -e`, so
 * a non-zero exit from commitlint aborts the commit. `npx --no` resolves the
 * locally installed commitlint without falling back to a network install. When
 * the config lives outside the project root, `--config <path>` points commitlint
 * at it.
 */
export function commitMsgHook(commitlintPath?: string): string {
    const base = 'npx --no -- commitlint --edit "$1"';
    return commitlintPath ? `${base} --config "${commitlintPath}"` : base;
}

/** The default commit-msg hook body (config at the project root). */
export const COMMIT_MSG_HOOK = commitMsgHook();

/** Normalize a commitlint output directory (no leading `./`, no trailing `/`). */
function normalizeDir(dir: string | undefined): string {
    if (!dir) return '';
    const value = dir
        .replace(/\\/g, '/')
        .replace(/^\.?\//, '')
        .replace(/\/+$/, '');
    if (/^[a-zA-Z]:/.test(value) || value.split('/').includes('..')) {
        throw new Error(`invalid commitlint directory "${dir}" (must stay inside the project).`);
    }
    return value;
}

/** The workflow file paths produced for a config. */
export function workflowFilePaths(config: ToolchainConfig): string[] {
    const workflows = declaredWorkflows(config);
    const files: string[] = [];
    for (const [id, filename] of Object.entries(WORKFLOW_FILENAMES) as [WorkflowId, string][]) {
        const setting = workflows[id];
        if (isEnabled(setting)) files.push(workflowFilePath(id, setting, filename));
    }
    const custom = sectionEnabled(config.ci) ? (sectionConfig(config.ci)?.custom ?? {}) : {};
    for (const [id, setting] of Object.entries(custom)) {
        const value = setting as WorkflowSetting;
        if (isEnabled(value)) files.push(workflowFilePath(id, value));
    }
    return [...new Set(files)];
}

/** The workflow file names (basenames) produced for a config. */
export function workflowFilenames(config: ToolchainConfig): string[] {
    return [...new Set(workflowFilePaths(config).map(file => file.split('/').pop() ?? file))];
}

/**
 * The CI/changelog sync task: writes the opted-in GitHub workflows, the
 * commitlint config and the local `commit-msg` hook from the loaded
 * `dbx.config.*`. Branches, triggers, steps, jobs and per-workflow tokens are
 * all taken from the config.
 */
export function changelogSyncTask(): SyncTask {
    return {
        name: 'changelog',
        // Workflows + commitlint belong at a repo root (or a single project).
        projectTypes: ['monorepo-root', 'project'],
        // The task also writes release/issues/sync/ci workflows, so it runs
        // whenever the `ci` section is enabled; the changelog-specific outputs
        // (pipeline config, commitlint) still require `ci.changelog`.
        enabled: config => sectionEnabled(config.ci),
        regenerate: config => regenerateEnabled(config.ci),
        run: ctx => {
            const ch = resolveChangelogConfig(ctx.config) ?? {};
            const commitlintConfig = sectionConfig(ch.commitlint);
            // commitlint + the commit hook belong to the opted-in changelog pipeline.
            const commitlint =
                changelogSectionEnabled(ctx.config) &&
                regenerateEnabled(ch as { regenerate?: boolean }) &&
                resolveCommitlintEnabled(ch);
            const files: ManagedFile[] = [];
            const workflowPaths = new Set<string>();
            const workflowConflicts: Record<string, string> = {};
            const managed = new Set(ctx.managedFiles ?? []);
            const isManagedWorkflow = (filePath: string): boolean => {
                if (managed.has(filePath)) return true;
                const abs = path.resolve(ctx.cwd, filePath);
                if (!fs.existsSync(abs)) return true;
                try {
                    const current = fs.readFileSync(abs, 'utf-8').replace(/^\uFEFF/, '');
                    // A generated header also proves dbx owns it (eg. a lost manifest).
                    // Accept the pre-3.0 header so an upgrade does not turn every
                    // existing workflow into a user-owned conflict.
                    return (
                        current.startsWith(WORKFLOW_HEADER) ||
                        current.startsWith(LEGACY_WORKFLOW_HEADER)
                    );
                } catch {
                    return false;
                }
            };
            const addWorkflow = (
                id: string,
                filePath: string,
                content: string,
                custom = false
            ): void => {
                if (workflowPaths.has(filePath)) {
                    ctx.warn(
                        `changelog: workflow path "${filePath}" is declared more than once; skipping the duplicate.`
                    );
                    return;
                }
                if (!isManagedWorkflow(filePath)) {
                    const key = custom ? `ci.custom.${id}` : `ci.${id}`;
                    workflowConflicts[filePath] = key;
                    ctx.warn(
                        `changelog: ${filePath} already exists and is not managed by dbx; leaving it untouched. ` +
                            `Set \`${key}: { enabled: false }\` in dbx.config to keep it explicit.`,
                        'changelog.existing-workflow'
                    );
                    return;
                }
                workflowPaths.add(filePath);
                files.push({ path: filePath, content });
            };

            const commitlintDir = normalizeDir(commitlintConfig?.dir);
            const commitlintPath = commitlintDir
                ? `${commitlintDir}/commitlint.config.mjs`
                : 'commitlint.config.mjs';

            const workflows = withBranchDefaults(
                declaredWorkflows(ctx.config),
                resolveChangelogBranches(ch)
            );
            const tokens = {
                ...ctx.tokens,
                commitlintConfig: commitlintPath,
                // Vite/Vite+ projects install `vp` with `voidzero-dev/setup-vp`
                // instead of the Node/Corepack/package-manager steps.
                vitePlus: usesVitePlus(ctx.cwd, ctx.config),
                // changesets owns version/changelog writes, including consuming
                // `.changeset/*.md`; the generated commit must stage those.
                changesets: usesChangesetsProvider(ch),
                // Custom release jobs read this to pass `gh release create
                // --prerelease` for a prerelease version.
                releasePrerelease: releasePrerelease(workflows.release),
            };

            for (const [id, filename] of Object.entries(WORKFLOW_FILENAMES) as [
                WorkflowId,
                string,
            ][]) {
                const setting = workflows[id];
                if (!isEnabled(setting)) continue;
                // A raw string is written verbatim (no generated header).
                const raw = typeof setting === 'string';
                const content = raw
                    ? setting
                    : isVendorWorkflowSetting(setting)
                      ? renderVendorWorkflow(setting, tokens)
                      : renderWorkflow(id, {
                            tokens,
                            config: typeof setting === 'object' ? (setting as WorkflowOptions) : {},
                            commitlint,
                        });
                if (!content) continue;
                addWorkflow(
                    id,
                    workflowFilePath(id, setting, filename),
                    raw ? content : `${WORKFLOW_HEADER}\n${content}`
                );
            }

            // Config-defined workflows (`ci.custom.<id>`): enabled by presence,
            // starting from an empty skeleton or written verbatim when a string.
            const custom = sectionEnabled(ctx.config.ci)
                ? (sectionConfig(ctx.config.ci)?.custom ?? {})
                : {};
            for (const [id, customSetting] of Object.entries(custom)) {
                const setting = customSetting as WorkflowSetting;
                if (!isEnabled(setting)) continue;
                const raw = typeof setting === 'string';
                const content = raw
                    ? setting
                    : isVendorWorkflowSetting(setting)
                      ? renderVendorWorkflow(setting, tokens)
                      : renderCustomWorkflow(id, {
                            tokens,
                            config: typeof setting === 'object' ? (setting as WorkflowOptions) : {},
                            commitlint,
                        });
                if (!content) continue;
                addWorkflow(
                    id,
                    workflowFilePath(id, setting),
                    raw ? content : `${WORKFLOW_HEADER}\n${content}`,
                    true
                );
            }

            // Dependabot version updates (`ci.dependabot`): a separate
            // `.github/dependabot.yml`, opt-in like every workflow.
            const dependabot = sectionEnabled(ctx.config.ci)
                ? sectionConfig(ctx.config.ci)?.dependabot
                : undefined;
            const dependabotOn =
                dependabot === true ||
                (typeof dependabot === 'object' &&
                    dependabot !== null &&
                    dependabot.enabled !== false);
            if (dependabotOn) {
                const setting = typeof dependabot === 'object' ? dependabot : {};
                const filePath = dependabotFilePath(setting);
                if (workflowPaths.has(filePath)) {
                    ctx.warn(
                        `changelog: workflow path "${filePath}" is declared more than once; skipping the duplicate.`
                    );
                } else if (!isManagedWorkflow(filePath)) {
                    ctx.warn(
                        `changelog: ${filePath} already exists and is not managed by dbx; leaving it untouched. ` +
                            'Set `ci.dependabot: { enabled: false }` in dbx.config to keep it explicit.',
                        'changelog.existing-dependabot'
                    );
                } else {
                    workflowPaths.add(filePath);
                    files.push({
                        path: filePath,
                        content: `${WORKFLOW_HEADER}\n${renderDependabot(setting)}`,
                        format: false,
                    });

                    // Security updates are a repository setting, not part of
                    // dependabot.yml: the generated workflow enables/disables
                    // them and applies the severity threshold.
                    const securityWorkflow = renderDependabotSecurityWorkflow(setting);
                    if (securityWorkflow !== undefined) {
                        if (workflowPaths.has(DEPENDABOT_SECURITY_FILE)) {
                            ctx.warn(
                                `changelog: workflow path "${DEPENDABOT_SECURITY_FILE}" is declared more than once; skipping the duplicate.`
                            );
                        } else if (!isManagedWorkflow(DEPENDABOT_SECURITY_FILE)) {
                            ctx.warn(
                                `changelog: ${DEPENDABOT_SECURITY_FILE} already exists and is not managed by dbx; leaving it untouched. ` +
                                    'Set `ci.dependabot.security: { workflow: false }` to keep it explicit.',
                                'changelog.existing-dependabot-security'
                            );
                        } else {
                            workflowPaths.add(DEPENDABOT_SECURITY_FILE);
                            files.push({
                                path: DEPENDABOT_SECURITY_FILE,
                                content: `${WORKFLOW_HEADER}\n${securityWorkflow}`,
                                format: false,
                            });
                        }
                    }
                }
            }

            if (commitlint) {
                files.push({
                    path: commitlintPath,
                    content: `${COMMITLINT_HEADER}\n${renderCommitlintConfig({
                        ...(commitlintConfig?.types ? { types: commitlintConfig.types } : {}),
                        ...(commitlintConfig?.scopes ? { scopes: commitlintConfig.scopes } : {}),
                    })}`,
                });

                // The local commit hook. Vite+ projects use the `.vite-hooks`
                // dispatcher (`vp hooks enable` / `vp config`), so it shares one
                // hook system with `vp staged`; projects without Vite+ keep the
                // husky fallback. The generated CI job lints the pushed range as
                // the backstop either way.
                files.push({
                    path: commitHookPath(ctx.cwd),
                    content: `${HOOK_HEADER}\n${commitMsgHook(commitlintDir ? commitlintPath : undefined)}\n`,
                });
            }

            if (ctx.manifest) {
                if (Object.keys(workflowConflicts).length > 0) {
                    ctx.manifest.workflowConflicts = workflowConflicts;
                } else {
                    delete ctx.manifest.workflowConflicts;
                }
            }

            return files;
        },
    };
}
