/**
 * Conventional-Commits supporting templates (commitlint config + the VS Code
 * settings/extensions). The GitHub Actions workflows are built as data in
 * `workflows.ts`.
 */

export interface CommitlintOptions {
    /** Allowed commit types (defaults to the Conventional-Commits set). */
    types?: string[];
    /** Allowed scopes (only enforced when a scope is present). */
    scopes?: string[];
}

const DEFAULT_TYPES = [
    'feat',
    'fix',
    'docs',
    'codegen',
    'style',
    'refactor',
    'perf',
    'test',
    'build',
    'ci',
    'chore',
    'revert',
    'release',
];

const DEFAULT_SCOPES = [
    'server',
    'frontend',
    'cli',
    'sdk',
    'scripts',
    'shared',
    'types',
    'ci',
    'docker',
    'security',
    'release',
    'deps',
];

/** Render a `commitlint.config.mjs` module string (Oxfmt-formatted). */
export function renderCommitlintConfig(options: CommitlintOptions = {}): string {
    const types = options.types ?? DEFAULT_TYPES;
    const scopes = options.scopes ?? DEFAULT_SCOPES;
    const list = (values: string[]): string =>
        values.map(value => `                '${value}',`).join('\n');
    return `/**
 * Conventional Commits enforcement (https://www.conventionalcommits.org/en/v1.0.0/).
 * Generated by @deltabox/toolchain-changelog.
 */
export default {
    extends: ['@commitlint/config-conventional'],
    rules: {
        'type-enum': [
            2,
            'always',
            [
${list(types)}
            ],
        ],
        'scope-enum': [
            2,
            'always',
            [
${list(scopes)}
            ],
        ],
        'body-max-line-length': [0],
        'footer-max-line-length': [0],
    },
};
`;
}

/** The recommended VS Code settings for Conventional Commits. */
