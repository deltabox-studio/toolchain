/**
 * Dockerfile / `.dockerignore` / compose generation.
 *
 * The generated artifacts are data-driven and multi-stage: Vite+ projects build
 * with the official `ghcr.io/voidzero-dev/vite-plus` image, Bun projects use
 * `oven/bun`, and other Node projects use the matching `node:<version>` image.
 * Static sites are served by the unprivileged nginx image. Runtime images run as
 * a non-root user and get an HTTP healthcheck by default.
 */

import fs from 'node:fs';
import path from 'node:path';

import { declaresVitePlus, type PackageJson, readJsonAt } from '@deltabox/toolchain/shared';

/** A generated Docker artifact. */
export interface DockerFile {
    /** Path relative to the project root. */
    path: string;
    /** File content. */
    content: string;
}

/** How the generated container runs. */
export type DockerRuntime = 'node' | 'static' | 'bun';

/** Options for generating the Docker artifacts. */
export interface DockerOptions {
    /** Container image name (default: the project name). */
    image?: string;
    /** Container image tag (default `latest`). */
    tag?: string;
    /** Container port to expose (default 3000, or 8080 for static sites). */
    port?: number;
    /** Runtime layout (default `auto`, detected from `package.json`). */
    runtime?: 'auto' | DockerRuntime;
    /** Built entry file, relative to the project root (default `dist/index.js`). */
    entry?: string;
    /** Build output directory (default `dist`, or the VitePress output). */
    output?: string;
    /** Node.js version for non-Vite+ images. */
    nodeVersion?: string;
    /** Override the build-stage base image. */
    baseImage?: string;
    /** Override the runtime base image. */
    runtimeImage?: string;
    /** Runtime user to run as. */
    user?: string;
    /** Also write `docker-compose.yaml` (default false). */
    compose?: boolean;
    /** Add a `HEALTHCHECK` to the runtime image (default true). */
    healthcheck?: boolean;
    /** HTTP path the healthcheck requests (default `/`). */
    healthcheckPath?: string;
    /** Dockerfile name (default `Dockerfile`). */
    dockerfile?: string;
    /** Write a `.dockerignore` alongside the Dockerfile (default true). */
    dockerignore?: boolean;
    /** Extra files/directories copied from the build stage into the runtime image. */
    assets?: string[];
    /** Runtime system packages installed with `apt-get` (eg. `rclone`). */
    runtimePackages?: string[];
    /**
     * Emit a runnable server image (default true). Set `false` for a library or
     * other package that has no server entry point: `dockerFiles` then emits no
     * artifacts at all instead of a broken Node image.
     */
    runnableServer?: boolean;
}

/** Options for planning/rendering the Docker artifacts for a project. */
export interface DockerPlanOptions extends DockerOptions {
    /** The project root. */
    cwd: string;
    /** The project/package name (used for the image name). */
    projectName?: string;
    /** The project's package manager. */
    packageManager?: string;
    /** Whether the project runs on Vite/Vite+. */
    vitePlus?: boolean;
}

/** Yarn Plug'n'Play files copied into a server image instead of `node_modules`. */
export interface PnpRuntime {
    /** The resolver entry (`.pnp.cjs`, or `.pnp.js` for older Yarn versions). */
    entry: string;
    /** The ESM loader, when the install generates one. */
    loader?: string;
    /** Every file/directory the runtime needs from the install stage. */
    files: string[];
}

/** The resolved plan a Dockerfile is rendered from. */
export interface DockerPlan {
    runtime: DockerRuntime;
    packageManager: string;
    nodeVersion: string;
    vitePlus: boolean;
    entry: string;
    output: string;
    port: number;
    image: string;
    tag: string;
    dockerfile: string;
    compose: boolean;
    dockerignore: boolean;
    healthcheck: boolean;
    healthcheckPath: string;
    user: string;
    baseImage: string;
    runtimeImage: string;
    /** The sources `COPY`ed before installing dependencies (only existing files). */
    installSources: string[];
    /** Whether `package.json` declares a `build` script. */
    hasBuildScript: boolean;
    /** Extra files/directories copied into the runtime image. */
    assets: string[];
    /** Runtime system packages installed with `apt-get`. */
    runtimePackages: string[];
    /** Whether the plan emits a runnable server image. */
    runnableServer: boolean;
    /** Yarn Plug'n'Play runtime files, when the project does not use `node_modules`. */
    pnp?: PnpRuntime;
}

/** The header prepended to every generated Docker artifact. */
export const DOCKER_HEADER = '# Generated by @deltabox/toolchain — this file is yours to edit.';
const VITE_PLUS_IMAGE = 'ghcr.io/voidzero-dev/vite-plus:latest';

/** Sanitize a package name into an OCI image name. */
export function dockerImageName(name: string): string {
    const unscoped = name.replace(/^@[^/]+\//, '');
    const cleaned = unscoped
        .toLowerCase()
        .replace(/[^a-z0-9._-]+/g, '-')
        .replace(/^[-.]+/, '')
        .replace(/[-.]+$/, '');
    return cleaned || 'app';
}

/** The major Node.js version (`>=22.10` -> `22`). */
function nodeMajor(value: string | undefined): string | undefined {
    const match = value?.match(/\d+/);
    return match?.[0];
}

/** The package manager from `package.json#packageManager` (`yarn@4.17.1` -> `yarn`). */
function declaredPackageManager(pkg: PackageJson | undefined): string | undefined {
    const value = pkg?.packageManager;
    if (typeof value !== 'string' || !value) return undefined;
    return value.split('@')[0];
}

/** Detect the package manager from the project's lockfile. */
function lockfilePackageManager(cwd: string): string | undefined {
    const has = (file: string): boolean => fs.existsSync(path.join(cwd, file));
    if (has('pnpm-lock.yaml')) return 'pnpm';
    if (has('yarn.lock')) return 'yarn';
    if (has('bun.lock') || has('bun.lockb')) return 'bun';
    if (has('package-lock.json')) return 'npm';
    return undefined;
}

/** The files `COPY`ed before installing dependencies (only those that exist). */
function installSources(packageManager: string, cwd: string, vitePlus = false): string[] {
    const has = (file: string): boolean => fs.existsSync(path.join(cwd, file));
    const sources = ['package.json'];
    // Vite+ resolves the Node.js version from `.node-version`; it must be in the
    // image before `vp install` runs, not only after the full `COPY . .`.
    if (vitePlus && has('.node-version')) sources.push('.node-version');
    switch (packageManager) {
        case 'pnpm':
            if (has('pnpm-lock.yaml')) sources.push('pnpm-lock.yaml');
            if (has('pnpm-workspace.yaml')) sources.push('pnpm-workspace.yaml');
            break;
        case 'npm':
            if (has('package-lock.json')) sources.push('package-lock.json');
            break;
        case 'bun':
            if (has('bun.lock')) sources.push('bun.lock');
            else if (has('bun.lockb')) sources.push('bun.lockb');
            break;
        default:
            if (has('yarn.lock')) sources.push('yarn.lock');
            if (has('.yarnrc.yml')) sources.push('.yarnrc.yml');
            // Yarn 4 re-executes the binary named by `yarnPath` and reads
            // patches/plugins from `.yarn/`; those sources must exist before the
            // install step (the full `COPY . .` only runs later).
            for (const dir of ['.yarn/releases', '.yarn/patches', '.yarn/plugins']) {
                if (has(dir)) sources.push(dir);
            }
    }
    return sources;
}

/** Whether a plan's copy sources include a lockfile a frozen install can use. */
function hasLockfile(sources: string[]): boolean {
    return sources.some(file =>
        /^(?:yarn\.lock|pnpm-lock\.yaml|package-lock\.json|bun\.lock|bun\.lockb)$/.test(file)
    );
}

/** The `nodeLinker` a `.yarnrc.yml` selects, if it declares one. */
function yarnNodeLinker(cwd: string): string | undefined {
    try {
        const contents = fs.readFileSync(path.join(cwd, '.yarnrc.yml'), 'utf-8');
        return contents.match(/^\s*nodeLinker:\s*['"]?([\w-]+)['"]?\s*$/m)?.[1];
    } catch {
        return undefined;
    }
}

/**
 * Detect Yarn Plug'n'Play. `nodeLinker: pnp` is enough before the first install
 * (the `.pnp.*` resolver is generated by that install); once installed, the
 * resolver file is authoritative.
 */
function pnpRuntime(packageManager: string, cwd: string): PnpRuntime | undefined {
    if (packageManager !== 'yarn') return undefined;
    const has = (file: string): boolean => fs.existsSync(path.join(cwd, file));
    const linker = yarnNodeLinker(cwd);
    if (linker === 'node-modules') return undefined;
    const entry = has('.pnp.js') && !has('.pnp.cjs') ? '.pnp.js' : '.pnp.cjs';
    if (!has(entry) && linker !== 'pnp') return undefined;
    const loader = has('.pnp.loader.mjs') ? '.pnp.loader.mjs' : undefined;
    return {
        entry,
        ...(loader ? { loader } : {}),
        files: [entry, ...(loader ? [loader] : []), '.yarn'],
    };
}

/** The install command for a Node image. */
function nodeInstall(packageManager: string, production = false, frozen = true): string {
    switch (packageManager) {
        case 'pnpm':
            return `corepack enable && pnpm install${frozen ? ' --frozen-lockfile' : ''}${production ? ' --prod' : ''}`;
        case 'npm':
            return frozen
                ? `npm ci${production ? ' --omit=dev' : ''}`
                : `npm install${production ? ' --omit=dev' : ''}`;
        case 'bun':
            return `bun install${frozen ? ' --frozen-lockfile' : ''}${production ? ' --production' : ''}`;
        default:
            return `corepack enable && yarn install${frozen ? ' --immutable' : ''}`;
    }
}

/** The build command for a runtime/package manager. */
function buildCommand(plan: DockerPlan): string {
    if (plan.runtime === 'bun') return 'bun run build';
    if (plan.vitePlus) return 'vp run build';
    return plan.packageManager === 'npm' ? 'npm run build' : `${plan.packageManager} run build`;
}

/** The directory sources that must keep their path (Docker flattens `COPY dir ./`). */
const DIRECTORY_SOURCES = new Set(['.yarn/releases', '.yarn/patches', '.yarn/plugins']);

/** The `COPY` lines for the pre-install sources, preserving directory names. */
function copySourceLines(plan: DockerPlan, chown?: string): string[] {
    const prefix = chown ? `COPY --chown=${chown} ` : 'COPY ';
    const files = plan.installSources.filter(source => !DIRECTORY_SOURCES.has(source));
    const lines: string[] = [];
    if (files.length > 0) lines.push(`${prefix}${files.join(' ')} ./`);
    for (const source of plan.installSources) {
        if (DIRECTORY_SOURCES.has(source)) lines.push(`${prefix}${source} ./${source}`);
    }
    return lines;
}

/** The install command for a Vite+ image. */
function vitePlusInstall(production = false, frozen = true): string {
    return `vp install${frozen ? ' --frozen-lockfile' : ''}${production ? ' --prod' : ''}`;
}

/** The default runtime user for a plan. */
function defaultUser(plan: DockerPlan): string {
    if (plan.runtime === 'bun') return 'bun';
    if (plan.vitePlus && plan.runtime === 'node') return 'nobody';
    if (plan.runtime === 'node') return 'node';
    return 'nginx';
}

/** The JSON-array healthcheck command for a runtime. */
function healthcheckCommand(plan: DockerPlan): string {
    const url = `http://127.0.0.1:${plan.port}${plan.healthcheckPath}`;
    if (plan.runtime === 'static') {
        return `HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 CMD wget -qO- ${url} >/dev/null || exit 1`;
    }
    const executable = plan.runtime === 'bun' ? 'bun' : 'node';
    const code = `fetch('${url}').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))`;
    return `HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 CMD ["${executable}", "-e", "${code}"]`;
}

/** Whether a build script produces a static Vite/Vite+ bundle. */
function isStaticViteBuild(build: string): boolean {
    return /(?:^|[\s;&|])(?:vite|vp)\s+build(?:\s|$)/.test(build);
}

/** Whether a start script only previews a static build. */
function isStaticPreview(start: string): boolean {
    return /(?:^|[\s;&|])(?:vite|vp)\s+preview(?:\s|$)/.test(start);
}

/** Validate the asset paths copied into the runtime image. */
function runtimeAssets(assets: string[] | undefined): string[] {
    return (assets ?? []).map(asset => {
        const normalized = asset
            .replace(/\\/g, '/')
            .replace(/^\.?\//, '')
            .replace(/\/+$/, '');
        if (
            !normalized ||
            path.posix.isAbsolute(normalized) ||
            normalized.split('/').includes('..')
        ) {
            throw new Error(`invalid Docker asset path "${asset}" (must be relative to the root).`);
        }
        return normalized;
    });
}

/** Validate the runtime system packages interpolated into the Dockerfile. */
function runtimePackages(packages: string[] | undefined): string[] {
    return (packages ?? []).map(name => {
        if (!/^[a-z0-9][a-z0-9.+-]*$/i.test(name)) {
            throw new Error(`invalid runtime package "${name}".`);
        }
        return name;
    });
}

/** Resolve the Docker plan for a project. */
export function resolveDockerPlan(options: DockerPlanOptions): DockerPlan {
    const pkg = readJsonAt<PackageJson>(options.cwd, 'package.json');
    const scripts = pkg?.scripts ?? {};
    const build = scripts.build ?? '';
    const start = scripts.start ?? '';
    const vitePlus = options.vitePlus ?? declaresVitePlus(options.cwd);
    const engines = (pkg as { engines?: { node?: string } } | undefined)?.engines;

    let runtime: DockerRuntime;
    if (options.runtime && options.runtime !== 'auto') runtime = options.runtime;
    else if (build.includes('vitepress')) runtime = 'static';
    else if (build.startsWith('bun ') || start.startsWith('bun ')) runtime = 'bun';
    // A Vite SPA with `start: vite preview` is static: the preview command is
    // not a server entry point, so a Node image would fail to start. An explicit
    // `runtime: 'node'` above still wins (a custom server can opt in).
    else if (isStaticPreview(start) || (!start && isStaticViteBuild(build))) runtime = 'static';
    else if (start) runtime = 'node';
    else if (isStaticViteBuild(build)) runtime = 'static';
    else runtime = 'node';

    // The package manager is the single source of truth for both the COPY
    // sources and the install command. A Bun-runtime project with no declared
    // manager installs with Bun; otherwise the declared manager wins so a
    // `yarn.lock` is never paired with `bun install`.
    const packageManager =
        options.packageManager ??
        declaredPackageManager(pkg) ??
        (runtime === 'bun' ? 'bun' : (lockfilePackageManager(options.cwd) ?? 'yarn'));

    const output =
        options.output ?? (build.includes('vitepress') ? 'docs/.vitepress/dist' : 'dist');
    const nodeVersion = nodeMajor(options.nodeVersion) ?? nodeMajor(engines?.node) ?? '22';
    const projectName = options.projectName ?? pkg?.name ?? 'app';
    const pnp = pnpRuntime(packageManager, options.cwd);

    const plan: DockerPlan = {
        runtime,
        packageManager,
        nodeVersion,
        vitePlus,
        entry: options.entry ?? 'dist/index.js',
        output,
        port: options.port ?? (runtime === 'static' ? 8080 : 3000),
        image: options.image ?? dockerImageName(projectName),
        tag: options.tag ?? 'latest',
        dockerfile: options.dockerfile ?? 'Dockerfile',
        compose: options.compose ?? false,
        dockerignore: options.dockerignore ?? true,
        healthcheck: options.healthcheck ?? true,
        healthcheckPath: options.healthcheckPath ?? '/',
        user: options.user ?? '',
        baseImage:
            options.baseImage ??
            // A Node runtime that installs/builds with Bun still needs the Bun
            // image for the build stage (the Node image has no `bun`). A Vite+
            // project keeps the Vite+ image: `vp install` resolves Bun itself.
            (runtime === 'bun' || (!vitePlus && packageManager === 'bun')
                ? 'oven/bun:1'
                : vitePlus
                  ? VITE_PLUS_IMAGE
                  : `node:${nodeVersion}-bookworm-slim`),
        runtimeImage:
            options.runtimeImage ??
            (runtime === 'bun'
                ? 'oven/bun:1-slim'
                : runtime === 'static'
                  ? 'nginxinc/nginx-unprivileged:alpine'
                  : vitePlus
                    ? 'debian:bookworm-slim'
                    : `node:${nodeVersion}-bookworm-slim`),
        installSources: installSources(packageManager, options.cwd, vitePlus),
        hasBuildScript: build.trim().length > 0,
        assets: runtimeAssets(options.assets),
        runtimePackages: runtimePackages(options.runtimePackages),
        runnableServer: options.runnableServer ?? true,
        ...(pnp ? { pnp } : {}),
    };
    plan.user = plan.user || defaultUser({ ...plan, vitePlus });
    return plan;
}

/** The build stage for a plan. */
function buildStage(plan: DockerPlan): string[] {
    const lines: string[] = [];
    const frozen = hasLockfile(plan.installSources);
    // A Bun-runtime project that declares another package manager needs both
    // runtimes: install with the declared manager in a Node stage, then build
    // with Bun. `oven/bun` has no npm/corepack, so installing in that image
    // would fail.
    const nodeDeps = plan.runtime === 'bun' && plan.packageManager !== 'bun';
    if (nodeDeps) {
        lines.push(
            `FROM node:${plan.nodeVersion}-bookworm-slim AS deps`,
            'WORKDIR /app',
            ...copySourceLines(plan),
            `RUN ${nodeInstall(plan.packageManager, false, frozen)}`,
            ''
        );
    }
    lines.push(`FROM ${plan.baseImage} AS build`, 'WORKDIR /app', '');
    if (plan.vitePlus && plan.runtime !== 'bun') {
        lines.push(
            ...copySourceLines(plan, 'vp:vp'),
            `RUN ${vitePlusInstall(false, frozen)}`,
            '',
            'COPY --chown=vp:vp . .'
        );
        if (plan.hasBuildScript) lines.push(`RUN ${buildCommand(plan)}`);
        return lines;
    }
    if (nodeDeps) {
        lines.push(
            // Copy the whole installed tree so both `node_modules` and Yarn PnP
            // files (`.pnp.cjs`, `.yarn`) reach the build stage.
            'COPY --from=deps /app ./',
            '',
            'COPY . .'
        );
        if (plan.hasBuildScript) lines.push(`RUN ${buildCommand(plan)}`);
        return lines;
    }
    lines.push(
        ...copySourceLines(plan),
        `RUN ${nodeInstall(plan.packageManager, false, frozen)}`,
        '',
        'COPY . .'
    );
    if (plan.hasBuildScript) lines.push(`RUN ${buildCommand(plan)}`);
    return lines;
}

/** The runtime stage for a static site. */
function staticRuntime(plan: DockerPlan): string[] {
    const lines = [
        `FROM ${plan.runtimeImage} AS runtime`,
        `COPY --from=build /app/${plan.output} /usr/share/nginx/html`,
    ];
    if (plan.port !== 8080) {
        lines.push(`RUN sed -i "s/8080/${plan.port}/g" /etc/nginx/conf.d/default.conf`);
    }
    lines.push(`EXPOSE ${plan.port}`);
    if (plan.healthcheck) lines.push(healthcheckCommand(plan));
    return lines;
}

/** The runtime stage for a Node/Bun server. */
function serverRuntime(plan: DockerPlan): string[] {
    const lines = [
        `FROM ${plan.runtimeImage} AS runtime`,
        'WORKDIR /app',
        'ENV NODE_ENV=production',
        'ENV HOST=0.0.0.0',
        `ENV PORT=${plan.port}`,
    ];
    if (plan.vitePlus && plan.runtime === 'node') {
        lines.push(
            'COPY --from=build /tmp/node /usr/local/bin/node',
            `COPY --from=build /app/${plan.output} ./${plan.output}`
        );
        if (plan.pnp) {
            for (const file of plan.pnp.files) {
                lines.push(`COPY --from=deps /app/${file} ./${file}`);
            }
        } else {
            lines.push('COPY --from=deps /app/node_modules ./node_modules');
        }
        lines.push('COPY --from=build /app/package.json ./');
    } else {
        lines.push(
            `COPY --from=build /app/${plan.output} ./${plan.output}`,
            'COPY --from=build /app/package.json ./'
        );
        if (plan.pnp) {
            for (const file of plan.pnp.files) {
                lines.push(`COPY --from=build /app/${file} ./${file}`);
            }
        } else {
            lines.push('COPY --from=build /app/node_modules ./node_modules');
        }
    }
    for (const asset of plan.assets) {
        lines.push(`COPY --from=build /app/${asset} ./${asset}`);
    }
    // Runtime system packages (eg. `rclone`) need root; install before dropping
    // to the unprivileged user.
    if (plan.runtimePackages.length > 0) {
        lines.push(
            `RUN apt-get update && apt-get install -y --no-install-recommends ${plan.runtimePackages.join(' ')} && rm -rf /var/lib/apt/lists/*`
        );
    }
    lines.push(`USER ${plan.user}`, `EXPOSE ${plan.port}`);
    if (plan.healthcheck) lines.push(healthcheckCommand(plan));
    lines.push(runtimeCommand(plan));
    return lines;
}

/** The runtime `CMD`, loading the Yarn PnP resolver when the project uses it. */
function runtimeCommand(plan: DockerPlan): string {
    if (plan.pnp && plan.runtime === 'node') {
        const args = ['node', '--require', `./${plan.pnp.entry}`];
        if (plan.pnp.loader) args.push('--experimental-loader', `./${plan.pnp.loader}`);
        args.push(plan.entry);
        return `CMD [${args.map(arg => `"${arg}"`).join(', ')}]`;
    }
    return `CMD ["${plan.runtime === 'bun' ? 'bun' : 'node'}", "${plan.entry}"]`;
}

/** Render the Dockerfile for a plan. */
export function renderDockerfile(plan: DockerPlan): string {
    const lines: string[] = [
        '# syntax=docker/dockerfile:1',
        DOCKER_HEADER,
        '',
        ...buildStage(plan),
    ];

    if (plan.vitePlus && plan.runtime === 'node') {
        lines.push(
            '',
            'RUN cp "$(vp env which node | head -1)" /tmp/node',
            '',
            `FROM ${plan.baseImage} AS deps`,
            'WORKDIR /app',
            ...copySourceLines(plan, 'vp:vp'),
            `RUN ${vitePlusInstall(true, hasLockfile(plan.installSources))}`
        );
    }

    lines.push('', ...(plan.runtime === 'static' ? staticRuntime(plan) : serverRuntime(plan)), '');
    return lines.join('\n');
}

/** A `.dockerignore` pattern that matches a path at any depth (including the root). */
function ignoreAnywhere(entry: string): string {
    const normalized = entry.replaceAll('\\', '/').replace(/^\.?\//, '');
    return normalized.startsWith('**/') ? normalized : `**/${normalized}`;
}

/** The default `.dockerignore` content. */
export function renderDockerignore(plan: DockerPlan): string {
    const lines = [
        ignoreAnywhere('node_modules'),
        ignoreAnywhere('dist'),
        ignoreAnywhere(plan.output),
        ignoreAnywhere('coverage'),
        ignoreAnywhere('.git'),
        ignoreAnywhere('.github'),
        ignoreAnywhere('.dbx'),
        ignoreAnywhere('*.log'),
        ignoreAnywhere('.env'),
        ignoreAnywhere('.env.*'),
        `!${ignoreAnywhere('.env.example')}`,
        `!${ignoreAnywhere('.env.example.*')}`,
    ];
    return [DOCKER_HEADER, ...new Set(lines), ''].join('\n');
}

/** The managed compose file name. */
export const DOCKER_COMPOSE_FILE = 'docker-compose.yaml';

/** Render an optional `docker-compose.yaml`. */
export function renderCompose(plan: DockerPlan): string {
    return [
        DOCKER_HEADER,
        'services:',
        '  app:',
        `    image: ${plan.image}:${plan.tag}`,
        '    build:',
        '      context: .',
        `      dockerfile: ${plan.dockerfile}`,
        '    ports:',
        `      - "${plan.port}:${plan.port}"`,
        '    environment:',
        '      NODE_ENV: production',
        '    restart: unless-stopped',
        '',
    ].join('\n');
}

/** Render every Docker artifact for a project. */
export function dockerFiles(options: DockerPlanOptions): DockerFile[] {
    const plan = resolveDockerPlan(options);
    // A library/non-server package has no runnable entry point: emitting a Node
    // server image would produce a container that exits immediately.
    if (!plan.runnableServer) return [];
    const files: DockerFile[] = [{ path: plan.dockerfile, content: renderDockerfile(plan) }];
    if (plan.dockerignore) {
        files.push({ path: '.dockerignore', content: renderDockerignore(plan) });
    }
    if (plan.compose) {
        files.push({ path: DOCKER_COMPOSE_FILE, content: renderCompose(plan) });
    }
    return files;
}

/** Write the Docker artifacts to a project (used after a Vite+ scaffold). */
export function writeDockerFiles(options: DockerPlanOptions & { force?: boolean }): string[] {
    const written: string[] = [];
    for (const file of dockerFiles(options)) {
        const target = path.resolve(options.cwd, file.path);
        if (!options.force && fs.existsSync(target)) continue;
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, file.content, 'utf-8');
        written.push(target);
    }
    return written;
}
