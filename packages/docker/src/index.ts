/**
 * Dockerfile / `.dockerignore` / compose generation.
 *
 * The generated artifacts are data-driven and multi-stage: Vite+ projects build
 * with the official `ghcr.io/voidzero-dev/vite-plus` image, Bun projects use
 * `oven/bun`, and other Node projects use the matching `node:<version>` image.
 * Static sites are served by the unprivileged nginx image. Runtime images run as
 * a non-root user and get an HTTP healthcheck by default.
 */

import fs from 'node:fs';
import path from 'node:path';

import { declaresVitePlus, type PackageJson, readJsonAt } from '@deltabox/toolchain/shared';

/** A generated Docker artifact. */
export interface DockerFile {
    /** Path relative to the project root. */
    path: string;
    /** File content. */
    content: string;
}

/** How the generated container runs. */
export type DockerRuntime = 'node' | 'static' | 'bun';

/** Options for generating the Docker artifacts. */
export interface DockerOptions {
    /** Container image name (default: the project name). */
    image?: string;
    /** Container image tag (default `latest`). */
    tag?: string;
    /** Container port to expose (default 3000, or 8080 for static sites). */
    port?: number;
    /** Runtime layout (default `auto`, detected from `package.json`). */
    runtime?: 'auto' | DockerRuntime;
    /** Built entry file, relative to the project root (default `dist/index.js`). */
    entry?: string;
    /** Build output directory (default `dist`, or the VitePress output). */
    output?: string;
    /** Node.js version for non-Vite+ images. */
    nodeVersion?: string;
    /** Override the build-stage base image. */
    baseImage?: string;
    /** Override the runtime base image. */
    runtimeImage?: string;
    /** Runtime user to run as. */
    user?: string;
    /** Also write `docker-compose.yaml` (default false). */
    compose?: boolean;
    /** Add a `HEALTHCHECK` to the runtime image (default true). */
    healthcheck?: boolean;
    /** HTTP path the healthcheck requests (default `/`). */
    healthcheckPath?: string;
    /** Dockerfile name (default `Dockerfile`). */
    dockerfile?: string;
    /** Write a `.dockerignore` alongside the Dockerfile (default true). */
    dockerignore?: boolean;
}

/** Options for planning/rendering the Docker artifacts for a project. */
export interface DockerPlanOptions extends DockerOptions {
    /** The project root. */
    cwd: string;
    /** The project/package name (used for the image name). */
    projectName?: string;
    /** The project's package manager. */
    packageManager?: string;
    /** Whether the project runs on Vite/Vite+. */
    vitePlus?: boolean;
}

/** The resolved plan a Dockerfile is rendered from. */
export interface DockerPlan {
    runtime: DockerRuntime;
    packageManager: string;
    nodeVersion: string;
    vitePlus: boolean;
    entry: string;
    output: string;
    port: number;
    image: string;
    tag: string;
    dockerfile: string;
    compose: boolean;
    dockerignore: boolean;
    healthcheck: boolean;
    healthcheckPath: string;
    user: string;
    baseImage: string;
    runtimeImage: string;
}

/** The header prepended to every generated Docker artifact. */
export const DOCKER_HEADER = '# Generated by @deltabox/toolchain — this file is yours to edit.';
const VITE_PLUS_IMAGE = 'ghcr.io/voidzero-dev/vite-plus:latest';

/** Sanitize a package name into an OCI image name. */
export function dockerImageName(name: string): string {
    const unscoped = name.replace(/^@[^/]+\//, '');
    const cleaned = unscoped
        .toLowerCase()
        .replace(/[^a-z0-9._-]+/g, '-')
        .replace(/^[-.]+/, '')
        .replace(/[-.]+$/, '');
    return cleaned || 'app';
}

/** The major Node.js version (`>=22.10` -> `22`). */
function nodeMajor(value: string | undefined): string | undefined {
    const match = value?.match(/\d+/);
    return match?.[0];
}

/** The package manager from `package.json#packageManager` (`yarn@4.17.1` -> `yarn`). */
function declaredPackageManager(pkg: PackageJson | undefined): string | undefined {
    const value = pkg?.packageManager;
    if (typeof value !== 'string' || !value) return undefined;
    return value.split('@')[0];
}

/** Detect the package manager from the project's lockfile. */
function lockfilePackageManager(cwd: string): string | undefined {
    const has = (file: string): boolean => fs.existsSync(path.join(cwd, file));
    if (has('pnpm-lock.yaml')) return 'pnpm';
    if (has('yarn.lock')) return 'yarn';
    if (has('bun.lock') || has('bun.lockb')) return 'bun';
    if (has('package-lock.json')) return 'npm';
    return undefined;
}

/** The files `COPY`ed before installing dependencies. */
function installSources(packageManager: string): string[] {
    switch (packageManager) {
        case 'pnpm':
            return ['package.json', 'pnpm-lock.yaml', 'pnpm-workspace.yaml', '.node-version*'];
        case 'npm':
            return ['package.json', 'package-lock.json', '.node-version*'];
        case 'bun':
            return ['package.json', 'bun.lock*', '.node-version*'];
        default:
            return ['package.json', 'yarn.lock', '.yarnrc.yml', '.node-version*'];
    }
}

/** The install command for a Node image. */
function nodeInstall(packageManager: string, production = false): string {
    switch (packageManager) {
        case 'pnpm':
            return `corepack enable && pnpm install --frozen-lockfile${production ? ' --prod' : ''}`;
        case 'npm':
            return production ? 'npm ci --omit=dev' : 'npm ci';
        case 'bun':
            return `bun install --frozen-lockfile${production ? ' --production' : ''}`;
        default:
            return 'corepack enable && yarn install --immutable';
    }
}

/** The build command for a runtime/package manager. */
function buildCommand(plan: DockerPlan): string {
    if (plan.runtime === 'bun') return 'bun run build';
    if (plan.vitePlus) return 'vp build';
    return plan.packageManager === 'npm' ? 'npm run build' : `${plan.packageManager} run build`;
}

/** The install command for a Vite+ image. */
function vitePlusInstall(production = false): string {
    return `vp install --frozen-lockfile${production ? ' --prod' : ''}`;
}

/** The default runtime user for a plan. */
function defaultUser(plan: DockerPlan): string {
    if (plan.runtime === 'bun') return 'bun';
    if (plan.vitePlus && plan.runtime === 'node') return 'nobody';
    if (plan.runtime === 'node') return 'node';
    return 'nginx';
}

/** The JSON-array healthcheck command for a runtime. */
function healthcheckCommand(plan: DockerPlan): string {
    const url = `http://127.0.0.1:${plan.port}${plan.healthcheckPath}`;
    if (plan.runtime === 'static') {
        return `HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 CMD wget -qO- ${url} >/dev/null || exit 1`;
    }
    const executable = plan.runtime === 'bun' ? 'bun' : 'node';
    const code = `fetch('${url}').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))`;
    return `HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 CMD ["${executable}", "-e", "${code}"]`;
}

/** Resolve the Docker plan for a project. */
export function resolveDockerPlan(options: DockerPlanOptions): DockerPlan {
    const pkg = readJsonAt<PackageJson>(options.cwd, 'package.json');
    const scripts = pkg?.scripts ?? {};
    const build = scripts.build ?? '';
    const start = scripts.start ?? '';
    const vitePlus = options.vitePlus ?? declaresVitePlus(options.cwd);
    const engines = (pkg as { engines?: { node?: string } } | undefined)?.engines;
    const packageManager =
        options.packageManager ??
        declaredPackageManager(pkg) ??
        lockfilePackageManager(options.cwd) ??
        'yarn';

    let runtime: DockerRuntime;
    if (options.runtime && options.runtime !== 'auto') runtime = options.runtime;
    else if (build.includes('vitepress')) runtime = 'static';
    else if (build.startsWith('bun ') || start.startsWith('bun ')) runtime = 'bun';
    else if (start) runtime = 'node';
    else if (build.includes('vp build')) runtime = 'static';
    else runtime = 'node';

    const output =
        options.output ?? (build.includes('vitepress') ? 'docs/.vitepress/dist' : 'dist');
    const nodeVersion = nodeMajor(options.nodeVersion) ?? nodeMajor(engines?.node) ?? '22';
    const projectName = options.projectName ?? pkg?.name ?? 'app';

    const plan: DockerPlan = {
        runtime,
        packageManager,
        nodeVersion,
        vitePlus,
        entry: options.entry ?? 'dist/index.js',
        output,
        port: options.port ?? (runtime === 'static' ? 8080 : 3000),
        image: options.image ?? dockerImageName(projectName),
        tag: options.tag ?? 'latest',
        dockerfile: options.dockerfile ?? 'Dockerfile',
        compose: options.compose ?? false,
        dockerignore: options.dockerignore ?? true,
        healthcheck: options.healthcheck ?? true,
        healthcheckPath: options.healthcheckPath ?? '/',
        user: options.user ?? '',
        baseImage:
            options.baseImage ??
            (runtime === 'bun'
                ? 'oven/bun:1'
                : vitePlus
                  ? VITE_PLUS_IMAGE
                  : `node:${nodeVersion}-bookworm-slim`),
        runtimeImage:
            options.runtimeImage ??
            (runtime === 'bun'
                ? 'oven/bun:1-slim'
                : runtime === 'static'
                  ? 'nginxinc/nginx-unprivileged:alpine'
                  : vitePlus
                    ? 'debian:bookworm-slim'
                    : `node:${nodeVersion}-bookworm-slim`),
    };
    plan.user = plan.user || defaultUser({ ...plan, vitePlus });
    return plan;
}

/** The build stage for a plan. */
function buildStage(plan: DockerPlan): string[] {
    const lines: string[] = [`FROM ${plan.baseImage} AS build`, 'WORKDIR /app', ''];
    if (plan.vitePlus && plan.runtime !== 'bun') {
        lines.push(
            `COPY --chown=vp:vp ${installSources(plan.packageManager).join(' ')} ./`,
            `RUN ${vitePlusInstall()}`,
            '',
            'COPY --chown=vp:vp . .',
            `RUN ${buildCommand(plan)}`
        );
        return lines;
    }
    lines.push(
        `COPY ${installSources(plan.packageManager).join(' ')} ./`,
        plan.runtime === 'bun'
            ? 'RUN bun install --frozen-lockfile'
            : `RUN ${nodeInstall(plan.packageManager)}`,
        '',
        'COPY . .',
        `RUN ${buildCommand(plan)}`
    );
    return lines;
}

/** The runtime stage for a static site. */
function staticRuntime(plan: DockerPlan): string[] {
    const lines = [
        `FROM ${plan.runtimeImage} AS runtime`,
        `COPY --from=build /app/${plan.output} /usr/share/nginx/html`,
        `EXPOSE ${plan.port}`,
    ];
    if (plan.healthcheck) lines.push(healthcheckCommand(plan));
    return lines;
}

/** The runtime stage for a Node/Bun server. */
function serverRuntime(plan: DockerPlan): string[] {
    const lines = [
        `FROM ${plan.runtimeImage} AS runtime`,
        'WORKDIR /app',
        'ENV NODE_ENV=production',
    ];
    if (plan.vitePlus && plan.runtime === 'node') {
        lines.push(
            'COPY --from=build /tmp/node /usr/local/bin/node',
            `COPY --from=build /app/${plan.output} ./${plan.output}`,
            'COPY --from=deps /app/node_modules ./node_modules',
            'COPY --from=build /app/package.json ./'
        );
    } else {
        lines.push(
            `COPY --from=build /app/${plan.output} ./${plan.output}`,
            'COPY --from=build /app/package.json ./',
            'COPY --from=build /app/node_modules ./node_modules'
        );
    }
    lines.push(`USER ${plan.user}`, `EXPOSE ${plan.port}`);
    if (plan.healthcheck) lines.push(healthcheckCommand(plan));
    lines.push(`CMD ["${plan.runtime === 'bun' ? 'bun' : 'node'}", "${plan.entry}"]`);
    return lines;
}

/** Render the Dockerfile for a plan. */
export function renderDockerfile(plan: DockerPlan): string {
    const lines: string[] = [
        '# syntax=docker/dockerfile:1',
        DOCKER_HEADER,
        '',
        ...buildStage(plan),
    ];

    if (plan.vitePlus && plan.runtime === 'node') {
        lines.push(
            '',
            'RUN cp "$(vp env which node | head -1)" /tmp/node',
            '',
            `FROM ${plan.baseImage} AS deps`,
            'WORKDIR /app',
            `COPY --chown=vp:vp ${installSources(plan.packageManager).join(' ')} ./`,
            `RUN ${vitePlusInstall(true)}`
        );
    }

    lines.push('', ...(plan.runtime === 'static' ? staticRuntime(plan) : serverRuntime(plan)), '');
    return lines.join('\n');
}

/** The default `.dockerignore` content. */
export function renderDockerignore(plan: DockerPlan): string {
    const lines = [
        'node_modules',
        'dist',
        plan.output,
        'coverage',
        '.git',
        '.github',
        '.dbx',
        '*.log',
        '.env',
        '.env.*',
        '!.env.example',
        '!.env.example.*',
    ];
    return [DOCKER_HEADER, ...new Set(lines), ''].join('\n');
}

/** The managed compose file name. */
export const DOCKER_COMPOSE_FILE = 'docker-compose.yaml';

/** Render an optional `docker-compose.yaml`. */
export function renderCompose(plan: DockerPlan): string {
    return [
        DOCKER_HEADER,
        'services:',
        '  app:',
        `    image: ${plan.image}:${plan.tag}`,
        '    build:',
        '      context: .',
        `      dockerfile: ${plan.dockerfile}`,
        '    ports:',
        `      - "${plan.port}:${plan.port}"`,
        '    environment:',
        '      NODE_ENV: production',
        '    restart: unless-stopped',
        '',
    ].join('\n');
}

/** Render every Docker artifact for a project. */
export function dockerFiles(options: DockerPlanOptions): DockerFile[] {
    const plan = resolveDockerPlan(options);
    const files: DockerFile[] = [{ path: plan.dockerfile, content: renderDockerfile(plan) }];
    if (plan.dockerignore) {
        files.push({ path: '.dockerignore', content: renderDockerignore(plan) });
    }
    if (plan.compose) {
        files.push({ path: DOCKER_COMPOSE_FILE, content: renderCompose(plan) });
    }
    return files;
}

/** Write the Docker artifacts to a project (used after a Vite+ scaffold). */
export function writeDockerFiles(options: DockerPlanOptions & { force?: boolean }): string[] {
    const written: string[] = [];
    for (const file of dockerFiles(options)) {
        const target = path.resolve(options.cwd, file.path);
        if (!options.force && fs.existsSync(target)) continue;
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, file.content, 'utf-8');
        written.push(target);
    }
    return written;
}
