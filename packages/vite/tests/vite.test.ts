import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import { DEFAULT_FMT_RULES, DEFAULT_LINT_RULES } from '@deltabox/toolchain-shared';

import {
    detectViteSpecifier,
    OXC_FMT_CONFIG_FILE,
    OXC_LINT_CONFIG_FILE,
    renderViteConfig,
    resolveVite,
    resolveVp,
    VP_COMMANDS,
    viteCommandName,
    viteConfigObject,
    viteProvider,
    viteSyncTask,
} from '../src/index.js';

const tmpDirs: string[] = [];

function makeTmp(): string {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dbx-vite-'));
    // A repo boundary so dependency detection never walks above the test dir.
    fs.mkdirSync(path.join(dir, '.git'));
    tmpDirs.push(dir);
    return dir;
}

afterEach(() => {
    for (const dir of tmpDirs.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
});

describe('vp command catalog', () => {
    it('namespaces command names', () => {
        expect(viteCommandName('dev')).toBe('vite:dev');
    });

    it('covers the documented vp commands', () => {
        const names = VP_COMMANDS.map(command => command.name);
        for (const expected of [
            'create',
            'migrate',
            'dev',
            'check',
            'test',
            'build',
            'pack',
            'run',
        ]) {
            expect(names).toContain(expected);
        }
    });

    it('keeps the provider commands in sync with the catalog', () => {
        const provider = viteProvider();
        expect(provider.id).toBe('vite-plus');
        expect(provider.binary).toBe('vp');
        expect(provider.commands).toHaveLength(VP_COMMANDS.length);
        expect(provider.commands.map(command => command.name)).toEqual(
            VP_COMMANDS.map(command => viteCommandName(command.name))
        );
    });
});

describe('vp resolution', () => {
    it('prefers a project-local shim', () => {
        const dir = makeTmp();
        const bin = path.join(dir, 'node_modules', '.bin');
        fs.mkdirSync(bin, { recursive: true });
        for (const name of ['vp', 'vp.cmd', 'vp.exe']) {
            fs.writeFileSync(path.join(bin, name), '');
        }
        expect(resolveVp(dir).source).toBe('local');
    });

    it('falls back to a known source everywhere else', () => {
        const resolved = resolveVp(makeTmp());
        expect(['global', 'npx']).toContain(resolved.source);
        expect(resolved.exe).toBeTruthy();
        if (resolved.source === 'npx') expect(resolved.args).toContain('vite-plus');
    });
});

describe('vite.config.ts shim', () => {
    it('renders the managed shim (the config is resolved at runtime)', () => {
        const source = renderViteConfig();
        expect(source).toContain('// Generated by @deltabox/toolchain');
        expect(source).toContain("import { resolveVite } from '@deltabox/toolchain/vite';");
        expect(source).toContain("import { defineConfig, type ViteUserConfig } from 'vite-plus';");
        expect(source).toContain(
            'export default defineConfig(resolveVite<ViteUserConfig>({ cwd: import.meta.dirname }));'
        );
        expect(source).not.toContain('{{');
    });

    it('renders a shim for a plain `vite` project', () => {
        const source = renderViteConfig('vite');
        expect(source).toContain("import { defineConfig, type UserConfig } from 'vite';");
        expect(source).toContain(
            'export default defineConfig(resolveVite<UserConfig>({ cwd: import.meta.dirname }));'
        );
    });

    it('preserves existing imports/comments and merges the defineConfig import', () => {
        const existing = [
            '// my custom header',
            "import defaultSomething, { defineConfig, type SomeType } from 'vite';",
            "import react from '@vitejs/plugin-react';",
            '',
            'export default defineConfig({ plugins: [react()] });',
            '',
        ].join('\n');
        const shim = renderViteConfig('vite', existing);
        expect(shim).toContain('// my custom header');
        expect(shim).toContain(
            "import defaultSomething, { defineConfig, type SomeType, type UserConfig } from 'vite';"
        );
        expect(shim).toContain("import react from '@vitejs/plugin-react';");
        expect(shim).toContain("import { resolveVite } from '@deltabox/toolchain/vite';");
        expect(shim).toContain(
            'export default defineConfig(resolveVite<UserConfig>({ cwd: import.meta.dirname }));'
        );
        // Regenerating from the shim is stable (idempotent).
        expect(renderViteConfig('vite', shim)).toBe(shim);
    });

    it('does not duplicate defineConfig when the import is already merged', () => {
        const existing = [
            "import { defineConfig, type ViteUserConfig } from 'vite-plus';",
            '',
            'export default defineConfig({});',
            '',
        ].join('\n');
        const shim = renderViteConfig('vite-plus', existing);
        const importLine = shim.split('\n').find(line => line.includes("from 'vite-plus'")) ?? '';
        expect((importLine.match(/defineConfig/g) ?? []).length).toBe(1);
        expect((importLine.match(/ViteUserConfig/g) ?? []).length).toBe(1);
    });

    it('strips the toolchain opt-out (`config`) from the resolved object', () => {
        const resolved = viteConfigObject({ config: false, fmt: { semi: true } });
        expect(resolved).not.toHaveProperty('config');
        expect(resolved.fmt).toMatchObject({ semi: true });
    });

    it('uses the shared fmt/lint defaults when opted in with `true`', () => {
        expect(viteConfigObject({ fmt: true, lint: true })).toEqual({
            fmt: DEFAULT_FMT_RULES,
            lint: DEFAULT_LINT_RULES,
        });
        expect(DEFAULT_FMT_RULES).not.toHaveProperty('sortImports');
    });

    it('merges fmt/lint options over the shared defaults', () => {
        const resolved = viteConfigObject({
            fmt: { semi: false, ignorePatterns: ['custom/**'] },
            lint: { rules: { eqeqeq: 'error' } },
        }) as {
            fmt: {
                semi: boolean;
                printWidth: number;
                ignorePatterns: string[];
                sortImports?: unknown;
            };
            lint: { ignorePatterns: string[]; rules: Record<string, string> };
        };
        expect(resolved.fmt.semi).toBe(false);
        expect(resolved.fmt.printWidth).toBe(DEFAULT_FMT_RULES.printWidth);
        expect(resolved.fmt.ignorePatterns).toEqual(['custom/**']);
        expect(resolved.fmt.sortImports).toBeUndefined();
        expect(resolved.lint.rules.eqeqeq).toBe('error');
        expect(resolved.lint.rules['no-var']).toBe('warn');
        expect(resolved.lint.ignorePatterns).toEqual(DEFAULT_LINT_RULES.ignorePatterns);
    });

    it('opts out of managing vite.config.ts with `config: false`', async () => {
        const ctx = {
            cwd: makeTmp(),
            projectType: 'project' as const,
            config: { vite: { config: false } },
            tokens: {},
            log: () => {},
            warn: () => {},
        };
        const task = viteSyncTask();
        expect(task.enabled?.(ctx.config)).toBe(true);
        expect(await task.run(ctx)).toEqual([]);
    });

    it('writes the shim when the section is enabled', async () => {
        const ctx = {
            cwd: makeTmp(),
            projectType: 'project' as const,
            config: { vite: { config: true } },
            tokens: {},
            log: () => {},
            warn: () => {},
        };
        expect(await viteSyncTask().run(ctx)).toEqual([
            { path: 'vite.config.ts', content: renderViteConfig() },
        ]);
    });

    it('uses a custom managed vite config file name', async () => {
        const ctx = {
            cwd: makeTmp(),
            projectType: 'project' as const,
            config: { vite: { config: 'config/vite.custom.ts' } },
            tokens: {},
            log: () => {},
            warn: () => {},
        };
        expect(await viteSyncTask().run(ctx)).toEqual([
            { path: 'config/vite.custom.ts', content: renderViteConfig() },
        ]);
    });

    it('writes the Oxc config files when fmt/lint are defined', async () => {
        const vite = { fmt: { semi: false }, lint: { rules: { eqeqeq: 'error' as const } } };
        const ctx = {
            cwd: makeTmp(),
            projectType: 'project' as const,
            config: { vite },
            ownConfig: { vite },
            tokens: {},
            log: () => {},
            warn: () => {},
        };
        const files = await viteSyncTask().run(ctx);
        const fmt = files?.find(file => file.path === OXC_FMT_CONFIG_FILE);
        const lint = files?.find(file => file.path === OXC_LINT_CONFIG_FILE);
        expect(JSON.parse(fmt?.content ?? '{}')).toMatchObject({
            $schema: './node_modules/oxfmt/configuration_schema.json',
            semi: false,
        });
        expect(JSON.parse(lint?.content ?? '{}')).toMatchObject({
            $schema: './node_modules/oxlint/configuration_schema.json',
            rules: { eqeqeq: 'error' },
        });
    });

    it('generates Oxc files from toolchain.fmt/lint.oxc without a vite section', async () => {
        const config = { fmt: { oxc: { semi: false } } };
        const ctx = {
            cwd: makeTmp(),
            projectType: 'project' as const,
            config,
            ownConfig: config,
            tokens: {},
            log: () => {},
            warn: () => {},
        };
        const files = await viteSyncTask().run(ctx);
        expect(files?.some(file => file.path === 'vite.config.ts')).toBe(false);
        const fmt = files?.find(file => file.path === OXC_FMT_CONFIG_FILE);
        expect(JSON.parse(fmt?.content ?? '{}').semi).toBe(false);
    });

    it('lets vite.fmt override fmt.oxc when generating the Oxc config', async () => {
        const config = {
            fmt: { oxc: { semi: false, singleQuote: true } },
            vite: { fmt: { singleQuote: false } },
        };
        const ctx = {
            cwd: makeTmp(),
            projectType: 'project' as const,
            config,
            ownConfig: config,
            tokens: {},
            log: () => {},
            warn: () => {},
        };
        const fmt = (await viteSyncTask().run(ctx))?.find(
            file => file.path === OXC_FMT_CONFIG_FILE
        );
        const parsed = JSON.parse(fmt?.content ?? '{}');
        expect(parsed.semi).toBe(false);
        expect(parsed.singleQuote).toBe(false);
    });

    it('warns when Biome and Oxc are configured together', async () => {
        const warnings: { message: string; id?: string }[] = [];
        const vite = { fmt: { semi: false } };
        const ctx = {
            cwd: makeTmp(),
            projectType: 'project' as const,
            config: { biome: true, vite },
            ownConfig: { biome: true, vite },
            tokens: {},
            log: () => {},
            warn: (message: string, id?: string) => warnings.push({ message, id }),
        };
        await viteSyncTask().run(ctx);
        expect(warnings).toEqual([
            {
                message: expect.stringContaining('Both Biome and Oxc'),
                id: 'biome.oxc-conflict',
            },
        ]);
    });

    it('skips Oxc files for a workspace that only inherits fmt/lint', async () => {
        const ctx = {
            cwd: makeTmp(),
            projectType: 'monorepo-workspace' as const,
            config: { vite: { fmt: {}, lint: {} } },
            ownConfig: {},
            tokens: {},
            log: () => {},
            warn: () => {},
        };
        const files = await viteSyncTask().run(ctx);
        expect(files?.some(file => file.path === OXC_FMT_CONFIG_FILE)).toBe(false);
        expect(files?.some(file => file.path === OXC_LINT_CONFIG_FILE)).toBe(false);
    });

    it('writes Oxc files for a workspace that overrides fmt/lint', async () => {
        const ctx = {
            cwd: makeTmp(),
            projectType: 'monorepo-workspace' as const,
            config: { vite: { fmt: { semi: false } } },
            ownConfig: { vite: { fmt: { semi: false } } },
            tokens: {},
            log: () => {},
            warn: () => {},
        };
        const files = await viteSyncTask().run(ctx);
        expect(files?.some(file => file.path === OXC_FMT_CONFIG_FILE)).toBe(true);
        expect(files?.some(file => file.path === OXC_LINT_CONFIG_FILE)).toBe(false);
    });
});

describe('vite dependency detection', () => {
    function writePkg(dir: string, devDependencies: Record<string, string>): void {
        fs.writeFileSync(path.join(dir, 'package.json'), JSON.stringify({ devDependencies }));
    }

    it('detects `vite` vs `vite-plus` from package.json (vite-plus wins)', () => {
        const vite = makeTmp();
        writePkg(vite, { vite: '^8.3.0' });
        expect(detectViteSpecifier(vite)).toBe('vite');

        const plus = makeTmp();
        writePkg(plus, { 'vite-plus': '^1.2.0' });
        expect(detectViteSpecifier(plus)).toBe('vite-plus');

        const both = makeTmp();
        writePkg(both, { vite: '^8.3.0', 'vite-plus': '^1.2.0' });
        expect(detectViteSpecifier(both)).toBe('vite-plus');
    });

    it('finds a hoisted dependency from the repository root', () => {
        const root = makeTmp();
        writePkg(root, { 'vite-plus': '^1.2.0' });
        const workspace = path.join(root, 'packages', 'app');
        fs.mkdirSync(workspace, { recursive: true });
        fs.writeFileSync(path.join(workspace, 'package.json'), JSON.stringify({ name: 'app' }));
        expect(detectViteSpecifier(workspace)).toBe('vite-plus');
    });

    it('writes the shim with the detected specifier', async () => {
        const dir = makeTmp();
        writePkg(dir, { vite: '^8.3.0' });
        const ctx = {
            cwd: dir,
            projectType: 'project' as const,
            config: { vite: { config: true } },
            tokens: {},
            log: () => {},
            warn: () => {},
        };
        expect(await viteSyncTask().run(ctx)).toEqual([
            { path: 'vite.config.ts', content: renderViteConfig('vite') },
        ]);
    });
});

describe('resolveVite', () => {
    it('resolves toolchain.vite from the nearest dbx.config.*', async () => {
        const dir = makeTmp();
        fs.writeFileSync(
            path.join(dir, 'dbx.config.json'),
            JSON.stringify({
                toolchain: { vite: { config: true, fmt: { semi: false, singleQuote: true } } },
            })
        );
        const config = await resolveVite({ cwd: dir });
        expect(config).toMatchObject({ fmt: { semi: false, singleQuote: true } });
        expect((config as { fmt: { printWidth: number } }).fmt.printWidth).toBe(
            DEFAULT_FMT_RULES.printWidth
        );
    });

    it('uses a passed dbx config without touching disk', async () => {
        const config = await resolveVite({
            toolchain: { vite: { test: { environment: 'node' } } },
        });
        expect(config).toEqual({ test: { environment: 'node' } });
    });

    it('merges inline `vite` overrides over the loaded section', async () => {
        const dir = makeTmp();
        fs.writeFileSync(
            path.join(dir, 'dbx.config.json'),
            JSON.stringify({
                toolchain: {
                    vite: { config: true, fmt: { semi: false, singleQuote: true } },
                },
            })
        );
        const config = await resolveVite({ cwd: dir, vite: { fmt: { semi: true } } });
        expect(config).toMatchObject({ fmt: { semi: true, singleQuote: true } });
    });

    it('applies inline `vite` overrides over a passed config', async () => {
        const config = await resolveVite({
            toolchain: { vite: { test: { environment: 'node' } } },
            vite: { build: { sourcemap: true } },
        });
        expect(config).toEqual({
            test: { environment: 'node' },
            build: { sourcemap: true },
        });
    });

    it('throws when no dbx.config.* exists', async () => {
        await expect(resolveVite({ cwd: makeTmp() })).rejects.toThrow(/dbx\.config/);
    });
});
