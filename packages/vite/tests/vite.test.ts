import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import {
    renderViteConfig,
    resolveVite,
    resolveVp,
    VP_COMMANDS,
    viteCommandName,
    viteConfigObject,
    viteProvider,
    viteSyncTask,
} from '../src/index.js';

const tmpDirs: string[] = [];

function makeTmp(): string {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dbx-vite-'));
    tmpDirs.push(dir);
    return dir;
}

afterEach(() => {
    for (const dir of tmpDirs.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
});

describe('vp command catalog', () => {
    it('namespaces command names', () => {
        expect(viteCommandName('dev')).toBe('vite:dev');
    });

    it('covers the documented vp commands', () => {
        const names = VP_COMMANDS.map(command => command.name);
        for (const expected of [
            'create',
            'migrate',
            'dev',
            'check',
            'test',
            'build',
            'pack',
            'run',
        ]) {
            expect(names).toContain(expected);
        }
    });

    it('keeps the provider commands in sync with the catalog', () => {
        const provider = viteProvider();
        expect(provider.id).toBe('vite-plus');
        expect(provider.binary).toBe('vp');
        expect(provider.commands).toHaveLength(VP_COMMANDS.length);
        expect(provider.commands.map(command => command.name)).toEqual(
            VP_COMMANDS.map(command => viteCommandName(command.name))
        );
    });
});

describe('vp resolution', () => {
    it('prefers a project-local shim', () => {
        const dir = makeTmp();
        const bin = path.join(dir, 'node_modules', '.bin');
        fs.mkdirSync(bin, { recursive: true });
        for (const name of ['vp', 'vp.cmd', 'vp.exe']) {
            fs.writeFileSync(path.join(bin, name), '');
        }
        expect(resolveVp(dir).source).toBe('local');
    });

    it('falls back to a known source everywhere else', () => {
        const resolved = resolveVp(makeTmp());
        expect(['global', 'npx']).toContain(resolved.source);
        expect(resolved.exe).toBeTruthy();
        if (resolved.source === 'npx') expect(resolved.args).toContain('vite-plus');
    });
});

describe('vite.config.ts shim', () => {
    it('renders the managed shim (the config is resolved at runtime)', () => {
        const source = renderViteConfig();
        expect(source).toContain('// Generated by @deltabox/toolchain');
        expect(source).toContain("import { resolveVite } from '@deltabox/toolchain/vite';");
        expect(source).toContain("import { defineConfig } from 'vite-plus';");
        expect(source).toContain('export default defineConfig(resolveVite());');
        expect(source).not.toContain('{{');
    });

    it('strips the toolchain opt-out (`config`) from the resolved object', () => {
        expect(viteConfigObject({ config: false, fmt: { semi: true } })).toEqual({
            fmt: { semi: true },
        });
    });

    it('opts out of managing vite.config.ts with `config: false`', async () => {
        const ctx = {
            cwd: makeTmp(),
            projectType: 'project' as const,
            config: { vite: { config: false } },
            tokens: {},
            log: () => {},
        };
        const task = viteSyncTask();
        expect(task.enabled?.(ctx.config)).toBe(true);
        expect(await task.run(ctx)).toEqual([]);
    });

    it('writes the shim when the section is enabled', async () => {
        const ctx = {
            cwd: makeTmp(),
            projectType: 'project' as const,
            config: { vite: { fmt: { semi: true } } },
            tokens: {},
            log: () => {},
        };
        expect(await viteSyncTask().run(ctx)).toEqual([
            { path: 'vite.config.ts', content: renderViteConfig() },
        ]);
    });
});

describe('resolveVite', () => {
    it('resolves toolchain.vite from the nearest dbx.config.*', async () => {
        const dir = makeTmp();
        fs.writeFileSync(
            path.join(dir, 'dbx.config.json'),
            JSON.stringify({
                toolchain: { vite: { config: true, fmt: { semi: false, singleQuote: true } } },
            })
        );
        const config = await resolveVite(undefined, { cwd: dir });
        expect(config).toEqual({ fmt: { semi: false, singleQuote: true } });
    });

    it('uses a passed dbx config without touching disk', async () => {
        const config = await resolveVite({
            toolchain: { vite: { test: { environment: 'node' } } },
        });
        expect(config).toEqual({ test: { environment: 'node' } });
    });

    it('throws when no dbx.config.* exists', async () => {
        await expect(resolveVite(undefined, { cwd: makeTmp() })).rejects.toThrow(/dbx\.config/);
    });
});
