/**
 * The `vite` sync task: manages a `vite.config.ts` (Vite + Vitest + Oxlint +
 * Oxfmt + Vite Task in one file) when the consumer enables the `vite` section.
 *
 * The whole Vite+ config lives in `dbx.config.*` under `toolchain.vite`, so the
 * only hand-authored root config is `dbx.config.*`; this task renders the root
 * `vite.config.ts` from it (`vp run`/`check`/`staged` do not accept `--config`,
 * so the file has to live at the root). The task is opt-in by section presence
 * and `vite: { config: false }` leaves a hand-written `vite.config.ts` alone.
 */

import {
    applyReplacementsDeep,
    isPlainObject,
    type Replacements,
    type SyncTask,
    sectionConfig,
    sectionEnabled,
    type ToolingViteConfig,
} from '@deltabox/toolchain-shared';

/**
 * Render an object literal as TypeScript source (unquoting identifier keys) so
 * the generated `vite.config.ts` reads like a hand-written config.
 */
export function renderObjectLiteral(value: unknown, indent = 0): string {
    if (Array.isArray(value)) {
        if (value.length === 0) return '[]';
        const inner = value.map(item => renderObjectLiteral(item, indent + 1)).join(', ');
        return `[${inner}]`;
    }
    if (isPlainObject(value)) {
        const entries = Object.entries(value);
        if (entries.length === 0) return '{}';
        const pad = '    '.repeat(indent + 1);
        const close = '    '.repeat(indent);
        const body = entries
            .map(([key, child]) => {
                const name = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
                return `${pad}${name}: ${renderObjectLiteral(child, indent + 1)}`;
            })
            .join(',\n');
        return `{\n${body}\n${close}}`;
    }
    return JSON.stringify(value);
}

/** The `vite` section with the toolchain opt-out (`config`) removed. */
export function viteConfigObject(config: ToolingViteConfig = {}): Record<string, unknown> {
    const { config: _config, ...vite } = config as Record<string, unknown>;
    return vite;
}

/**
 * Serialize the Vite+ config to a `vite.config.ts` module: a managed-file header,
 * the `vite-plus` import and `defineConfig(<the toolchain.vite object>)`.
 */
export function renderViteConfig(
    config: ToolingViteConfig = {},
    tokens: Replacements = {}
): string {
    const vite = applyReplacementsDeep(viteConfigObject(config), tokens);
    return (
        '// Generated by @deltabox/toolchain — edit the vite section in dbx.config and run `dbx sync`.\n' +
        "import { defineConfig } from 'vite-plus';\n\n" +
        `export default defineConfig(${renderObjectLiteral(vite)});\n`
    );
}

/**
 * The vite sync task: writes `vite.config.ts` when the `vite` section is enabled
 * (and `config` is not `false`). Runs for every project kind.
 */
export function viteSyncTask(): SyncTask {
    return {
        name: 'vite',
        projectTypes: ['monorepo-root', 'monorepo-workspace', 'project'],
        enabled: config => sectionEnabled(config.vite),
        run: ctx => {
            const section = sectionConfig(ctx.config.vite) ?? {};
            if (section.config === false) return [];
            return [{ path: 'vite.config.ts', content: renderViteConfig(section, ctx.tokens) }];
        },
    };
}
